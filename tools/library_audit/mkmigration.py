"""Writes migrations/repair_library_queries.sql from fixed_library.json.
Each column is replaced only while it still holds the text the audit started from (md5 guard,
carriage returns ignored), so analyst edits made in the Artifact Library Editor are kept.
usage: python mkmigration.py QUALITY_DIR REPO_DIR"""
import hashlib, json, os, sys
QD, REPO = sys.argv[1], sys.argv[2]
CR = chr(13)
lib = {r["t"]: r for r in json.load(open(os.path.join(QD, "library.json"), encoding="utf-8"))}
fx = json.load(open(os.path.join(QD, "fixed_library.json"), encoding="utf-8"))
TAG = "$orcafix$"
out = ["-- Repairs artifact-library queries that could never match (see docs/LIBRARY_QUALITY.md).",
       "-- Generated by the library quality audit (2026-11-12). Each column is replaced only while it still",
       "-- holds the shipped text (md5 guard, line endings ignored): queries edited in the Artifact Library Editor are kept.",
       "-- Classes fixed: event read from the wrong log; System.EventID compared without .Value; regexes whose",
       "-- backslashes VQL string escaping consumed; fields that don't exist in the event; undefined names in",
       "-- WHERE; numbers compared to text; always-blank output columns; time windows relative to now();",
       "-- artifact names Velociraptor rejects; ORDER BY with several columns.",
       ""]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from holdback import held_back
hb = held_back(QD)
if hb:
    out.append("-- Held back (the repaired query returns thousands of rows on a normal workstation: it needs a real")
    out.append("-- content filter first): " + ", ".join(sorted(hb)))
    out.append("")
n = 0
for t in sorted(fx):
    if t in hb:
        continue
    f, o = fx[t], lib[t]
    for col, key in (("surgical_yaml", "y"), ("custom_vql", "v")):
        old = (o[key] or "").replace(CR, "")
        new = (f[key] or "").replace(CR, "")
        if new == old or not new:
            continue
        assert TAG not in new
        md5 = hashlib.md5(old.encode("utf-8")).hexdigest()
        out.append(f"UPDATE ref_artifact_library SET {col} = {TAG}{new}{TAG}, updated_at = NOW()")
        # installs differ only in line endings (CRLF live, LF from the seed file), so they're ignored
        out.append(f"WHERE t_code = '{t}' AND md5(replace(COALESCE({col}, ''), chr(13), '')) = '{md5}';")
        out.append("")
        n += 1
path = os.path.join(REPO, "migrations", "repair_library_queries.sql")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{n} column updates written to {path}")
